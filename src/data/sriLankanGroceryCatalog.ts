/**
 * Merge master Sri Lankan catalog with existing products safely.
 * Existing items retain their IDs, prices, stock levels, and existing cloud/local images.
 */
export function mergeMasterSriLankanCatalog(existingProducts: Product[]): Product[] {
  const existingMap = new Map<string, Product>();
  for (const p of existingProducts) {
    existingMap.set(p.id, p);
  }

  const result = [...existingProducts];
  for (const masterProd of SRI_LANKAN_MASTER_PRODUCTS) {
    if (!existingMap.has(masterProd.id)) {
      result.push(masterProd);
    }
  }

  return result;
}
